export const i18n = $state({ lang: (localStorage.getItem('lang') as 'en' | 'bg') || 'en' })

export function setLang(l: 'en' | 'bg') {
  i18n.lang = l
  localStorage.setItem('lang', l)
  document.documentElement.lang = l
}

export function t(k: Key, params?: Record<string, string | number>): string {
  let s = (i18n.lang === 'bg' ? bg : en)[k] ?? k
  if (params) for (const [p, v] of Object.entries(params)) s = s.replace(`{${p}}`, String(v))
  return s
}

export function locale(): string {
  return i18n.lang === 'bg' ? 'bg-BG' : 'en-GB'
}
